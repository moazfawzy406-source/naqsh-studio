fn map() -> &'static HashMap<&'static str, &'static str> {
    static M: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    M.get_or_init(|| TABLE.iter().copied().collect())
}

/// `label` in the UI language. A label with a line break keeps two lines in Arabic.
pub fn tr(label: &str) -> Cow<'_, str> {
    if !is_arabic() {
        return Cow::Borrowed(label);
    }
    let key = label.replace('\n', " ");
    match map().get(key.as_str()) {
        Some(ar) if label.contains('\n') => {
            let words: Vec<&str> = ar.split(' ').collect();
            if words.len() < 2 {
                Cow::Borrowed(ar)
            } else {
                let cut = words.len().div_ceil(2);
                Cow::Owned(format!("{}\n{}", words[..cut].join(" "), words[cut..].join(" ")))
            }
        }
        Some(ar) => Cow::Borrowed(ar),
        None => Cow::Borrowed(label),
    }
}
